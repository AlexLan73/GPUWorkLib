void FormScriptGenerator::ReleaseGpuResources() {
  if (program_) {
    clReleaseProgram(program_);
    program_ = nullptr;
  }
}

void FormScriptGenerator::VersionOldFiles(const std::string& name) const {
  std::string kdir = GetKernelsDir();
  std::string bdir = GetKernelsBinDir();
  std::string cl_path = kdir + "/" + name + ".cl";
  std::string bin_path = bdir + "/" + name + "_opencl.bin";

  bool cl_exists = fs::exists(cl_path);
  bool bin_exists = fs::exists(bin_path);

  if (!cl_exists && !bin_exists) return;

  // Find next free suffix: _00, _01, ...
  int suffix = 0;
  while (true) {
    char buf[8];
    snprintf(buf, sizeof(buf), "_%02d", suffix);
    std::string s(buf);

    std::string old_cl = kdir + "/" + name + s + ".cl";
    std::string old_bin = bdir + "/" + name + "_opencl" + s + ".bin";

    if (!fs::exists(old_cl) && !fs::exists(old_bin)) {
      // Rename current → _XX
      if (cl_exists)  fs::rename(cl_path, old_cl);
      if (bin_exists) fs::rename(bin_path, old_bin);
      return;
    }
    ++suffix;
    if (suffix > 99) break;  // safety
  }
}

void FormScriptGenerator::WriteManifestEntry(
    const std::string& name, const std::string& comment) const {
  std::string manifest_path = GetKernelsDir() + "/manifest.json";

  // Read existing manifest or start fresh
  std::string content;
  if (fs::exists(manifest_path)) {
    std::ifstream f(manifest_path);
    content.assign((std::istreambuf_iterator<char>(f)),
                    std::istreambuf_iterator<char>());
  }

  // Check if this name already exists — update or append
  std::string timestamp = GetTimestamp();
  std::string params_str = ParamsToString();

  // Build new entry JSON
  std::ostringstream entry;
  entry << "    {\n";
  entry << "      \"name\": \"" << name << "\",\n";
  entry << "      \"comment\": \"" << comment << "\",\n";
  entry << "      \"created\": \"" << timestamp << "\",\n";
  entry << "      \"params\": \"" << params_str << "\",\n";
  entry << "      \"backend\": \"opencl\"\n";
  entry << "    }";

  // Simple approach: rewrite manifest with all existing + new/updated
  // Parse existing entries (skip entry with same name)
  std::vector<std::string> entries;
  if (!content.empty()) {
    // Find entries between [ and ]
    size_t arr_start = content.find('[');
    size_t arr_end = content.rfind(']');
    if (arr_start != std::string::npos && arr_end != std::string::npos) {
      std::string arr = content.substr(arr_start + 1, arr_end - arr_start - 1);

      // Split by "}" and reconstruct
      size_t pos = 0;
      while (true) {
        size_t obj_start = arr.find('{', pos);
        if (obj_start == std::string::npos) break;
        size_t obj_end = arr.find('}', obj_start);
        if (obj_end == std::string::npos) break;

        std::string obj = arr.substr(obj_start, obj_end - obj_start + 1);

        // Check if this is the same name
        bool same_name = false;
        std::string name_check = "\"name\": \"" + name + "\"";
        if (obj.find(name_check) != std::string::npos) {
          same_name = true;
        }
        // Also check without space
        name_check = "\"name\":\"" + name + "\"";
        if (obj.find(name_check) != std::string::npos) {
          same_name = true;
        }

        if (!same_name) {
          // Re-indent
          entries.push_back("    " + obj);
        }

        pos = obj_end + 1;
      }
    }
  }

  // Add new entry
  entries.push_back(entry.str());

  // Write manifest
  std::ofstream f(manifest_path);
  f << "{\n";
  f << "  \"version\": 1,\n";
  f << "  \"kernels\": [\n";
  for (size_t i = 0; i < entries.size(); ++i) {
    f << entries[i];
    if (i + 1 < entries.size()) f << ",";
    f << "\n";
  }
  f << "  ]\n";
  f << "}\n";
}

std::vector<unsigned char> FormScriptGenerator::GetProgramBinary() const {
  if (!program_) {
    throw std::runtime_error("GetProgramBinary: no compiled program");
  }

  size_t binary_size = 0;
  cl_int err = clGetProgramInfo(program_, CL_PROGRAM_BINARY_SIZES,
                                 sizeof(size_t), &binary_size, nullptr);
  if (err != CL_SUCCESS || binary_size == 0) {
    throw std::runtime_error("GetProgramBinary: cannot get binary size");
  }

  std::vector<unsigned char> binary(binary_size);
  unsigned char* ptrs[] = { binary.data() };
  err = clGetProgramInfo(program_, CL_PROGRAM_BINARIES,
                          sizeof(unsigned char*), ptrs, nullptr);
  if (err != CL_SUCCESS) {
    throw std::runtime_error("GetProgramBinary: cannot get binary");
  }

  return binary;
}

void FormScriptGenerator::LoadFromBinary(
    const std::vector<unsigned char>& binary) {
  ReleaseGpuResources();

  cl_int err, binary_status;
  size_t bin_size = binary.size();
  const unsigned char* bin_ptr = binary.data();

  program_ = clCreateProgramWithBinary(
      context_, 1, &device_, &bin_size, &bin_ptr, &binary_status, &err);

  if (err != CL_SUCCESS || binary_status != CL_SUCCESS) {
    program_ = nullptr;
    throw std::runtime_error(
        "LoadFromBinary: clCreateProgramWithBinary failed");
  }

  err = clBuildProgram(program_, 1, &device_,
                       "-cl-fast-relaxed-math", nullptr, nullptr);
  if (err != CL_SUCCESS) {
    clReleaseProgram(program_);
    program_ = nullptr;
    throw std::runtime_error("LoadFromBinary: clBuildProgram failed");
  }
}

void FormScriptGenerator::LoadFromSource(const std::string& source) {
  CompileSource(source);
}

std::string FormScriptGenerator::GetTimestamp() {
  auto now = std::chrono::system_clock::now();
  auto t = std::chrono::system_clock::to_time_t(now);
  std::tm tm_buf;
  localtime_r(&t, &tm_buf);

  char buf[32];
  std::strftime(buf, sizeof(buf), "%Y-%m-%dT%H:%M:%S", &tm_buf);
  return std::string(buf);
}

std::string FormScriptGenerator::ParamsToString() const {
  std::ostringstream s;
  s << "fs=" << params_.fs
    << ",f0=" << params_.f0
    << ",a=" << params_.amplitude
    << ",an=" << params_.noise_amplitude
    << ",antennas=" << params_.antennas
    << ",points=" << params_.points;
  if (params_.fdev != 0.0) s << ",fdev=" << params_.fdev;
  if (params_.phase != 0.0) s << ",phi=" << params_.phase;
  if (params_.tau_base != 0.0) s << ",tau=" << params_.tau_base;
  if (params_.tau_step != 0.0) s << ",tau_step=" << params_.tau_step;
  return s.str();
}

