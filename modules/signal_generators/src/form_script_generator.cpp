// PRNG source (shared with FormSignalGenerator)
// ════════════════════════════════════════════════════════════════════════════

static const char* PRNG_SOURCE = R"CL(
// Philox-2x32-10: counter-based PRNG
uint2 philox2x32_round(uint2 ctr, uint key) {
    const uint PHILOX_M = 0xD2511F53u;
    uint hi = mul_hi(ctr.x, PHILOX_M);
    uint lo = ctr.x * PHILOX_M;
    return (uint2)(hi ^ key ^ ctr.y, lo);
}

uint2 philox2x32_10(uint2 ctr, uint key) {
    const uint PHILOX_BUMP = 0x9E3779B9u;
    ctr = philox2x32_round(ctr, key); key += PHILOX_BUMP;
    ctr = philox2x32_round(ctr, key); key += PHILOX_BUMP;
    ctr = philox2x32_round(ctr, key); key += PHILOX_BUMP;
    ctr = philox2x32_round(ctr, key); key += PHILOX_BUMP;
    ctr = philox2x32_round(ctr, key); key += PHILOX_BUMP;
    ctr = philox2x32_round(ctr, key); key += PHILOX_BUMP;
    ctr = philox2x32_round(ctr, key); key += PHILOX_BUMP;
    ctr = philox2x32_round(ctr, key); key += PHILOX_BUMP;
    ctr = philox2x32_round(ctr, key); key += PHILOX_BUMP;
    ctr = philox2x32_round(ctr, key);
    return ctr;
}

float philox_uniform(uint id, uint seed) {
    uint2 ctr = (uint2)(id, seed);
    uint2 rnd = philox2x32_10(ctr, 0xAB12CD34u);
    return (float)(rnd.x) / 4294967296.0f;
}
)CL";

// ════════════════════════════════════════════════════════════════════════════
// Constructor / Destructor
// ════════════════════════════════════════════════════════════════════════════

FormScriptGenerator::FormScriptGenerator(drv_gpu_lib::IBackend* backend)
    : backend_(backend) {
  if (!backend_ || !backend_->IsInitialized()) {
    throw std::runtime_error(
        "FormScriptGenerator: backend is null or not initialized");
  }
  context_ = static_cast<cl_context>(backend_->GetNativeContext());
  queue_   = static_cast<cl_command_queue>(backend_->GetNativeQueue());
  device_  = static_cast<cl_device_id>(backend_->GetNativeDevice());
}

FormScriptGenerator::~FormScriptGenerator() {
  ReleaseGpuResources();
}

FormScriptGenerator::FormScriptGenerator(FormScriptGenerator&& o) noexcept
    : backend_(o.backend_), params_(o.params_),
      kernel_source_(std::move(o.kernel_source_)),
      loaded_kernel_name_(std::move(o.loaded_kernel_name_)),
      context_(o.context_), queue_(o.queue_),
      device_(o.device_), program_(o.program_) {
  o.program_ = nullptr;
}

FormScriptGenerator& FormScriptGenerator::operator=(
    FormScriptGenerator&& o) noexcept {
  if (this != &o) {
    ReleaseGpuResources();
    backend_ = o.backend_;
    params_ = o.params_;
    kernel_source_ = std::move(o.kernel_source_);
    loaded_kernel_name_ = std::move(o.loaded_kernel_name_);
    context_ = o.context_;
    queue_ = o.queue_;
    device_ = o.device_;
    program_ = o.program_;
    o.program_ = nullptr;
  }
  return *this;
}

